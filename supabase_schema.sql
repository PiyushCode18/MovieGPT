-- 4. Chat History (Optional)
-- If you want to sync chat history across devices instead of just SharedPreferences.
CREATE TABLE IF NOT EXISTS public.chat_history (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  message_id TEXT NOT NULL,
  sender TEXT NOT NULL, -- 'user' or 'ai'
  text TEXT NOT NULL,
  timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
  assistant_mode TEXT, -- 'female', 'male', 'assistant'
  recommended_movies JSONB, -- list of movie objects
  is_error BOOLEAN DEFAULT false,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Enable RLS on Chat History
ALTER TABLE public.chat_history ENABLE ROW LEVEL SECURITY;

